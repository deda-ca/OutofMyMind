// Builds the release: one executable (Bun) with the server, the web client,
// the MCP plugins, the services kit and ONNX Runtime inside, and a tarball of
// it for deploying. For this machine's platform (linux-x64 or linux-arm64).
//
//   npm run build          (needs `npm run setup` once, and Bun)
//
// Output in dist/: jarvis-<version>-<platform>/ and its .tar.gz (+ .sha256).

import { execFileSync } from 'node:child_process'
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import type { BunPlugin } from 'bun'
import { PLUGINS } from './plugins.ts'

const ROOT = path.resolve(import.meta.dir, '..')
const at = (...p: string[]) => path.join(ROOT, ...p)
const GENERATED = at('release', '.generated')
const run = (cmd: string, args: string[], cwd = ROOT) => execFileSync(cmd, args, { cwd, stdio: 'inherit' })
const git = (...args: string[]) => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trim()

if (process.platform !== 'linux') throw new Error(`release builds are for Linux (this is ${process.platform})`)
const PLATFORM = `linux-${process.arch}`
const version = JSON.parse(fs.readFileSync(at('apps', 'server', 'package.json'), 'utf8')).version as string
const commit = git('rev-parse', '--short', 'HEAD') + (git('status', '--porcelain') ? '-dirty' : '')
const name = `jarvis-${version}-${PLATFORM}`
const out = at('dist', name)

// 1. The web client.
console.log('· web client')
run('npm', ['--prefix', 'apps/client', 'run', 'build'])

// 2. What the binary carries as files: [path where it's unpacked, file in the repository].
const walk = (dir: string): string[] => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]))
const files = (dir: string, keep: (f: string) => boolean = () => true) => walk(dir).filter(keep).map((f) => [path.relative(dir, f), f] as [string, string])
const site = files(at('apps', 'client', 'dist'))
const kit = files(at('apps', 'server', 'src', 'services', 'kit'), (f) => f.endsWith('.ts'))
const ortDir = at('apps', 'server', 'node_modules', 'onnxruntime-node', 'bin', 'napi-v6', 'linux', process.arch)
const ort = ['onnxruntime_binding.node', 'libonnxruntime.so.1'].map((f) => [f, path.join(ortDir, f)] as [string, string])
for (const [, f] of ort) if (!fs.existsSync(f)) throw new Error(`${f} is missing: run npm run setup`)

// 3. mcp.json, with each plugin started by the binary instead of node.
const BY_SCRIPT = new Map(Object.entries(PLUGINS).map(([plugin, p]) => [at(p.script), plugin]))
const mcp = JSON.parse(fs.readFileSync(at('apps', 'server', 'mcp.json'), 'utf8')) as { mcpServers: Record<string, { command?: string; args?: string[] }> }
for (const [server, entry] of Object.entries(mcp.mcpServers)) {
  if (entry.command !== 'node') continue
  const [script = '', ...args] = entry.args ?? []
  const plugin = BY_SCRIPT.get(path.resolve(at('apps', 'server'), script))
  if (!plugin) throw new Error(`mcp.json: "${server}" runs ${script}, which isn't built in: add it to release/plugins.ts`)
  Object.assign(entry, { command: '${JARVIS_BIN}', args: ['plugin', plugin, ...args] })
}
const mcpJson = `${JSON.stringify(mcp, null, 2)}\n`

// 4. The module that embeds them (import … with { type: 'file' }: a path readable at run time).
const hash = crypto.createHash('sha256')
for (const [rel, f] of [...site, ...kit, ...ort]) hash.update(rel).update(fs.readFileSync(f))
const build = { version, commit, date: new Date().toISOString().slice(0, 10), id: `${version}-${hash.digest('hex').slice(0, 12)}` }
let n = 0
const imports: string[] = []
const list = (entries: [string, string][]) => {
  const items = entries.map(([rel, f]) => {
    const id = `f${n++}`
    imports.push(`import ${id} from ${JSON.stringify(path.relative(GENERATED, f))} with { type: 'file' }`)
    return `  [${JSON.stringify(rel)}, ${id}],`
  })
  return `[\n${items.join('\n')}\n]`
}
const body = [
  `export const SITE: [string, string][] = ${list(site)}`,
  `export const KIT: [string, string][] = ${list(kit)}`,
  `export const ORT: [string, string][] = ${list(ort)}`,
  `export const BUILD = ${JSON.stringify(build)}`,
  `export const MCP_JSON = ${JSON.stringify(mcpJson)}`,
]
fs.rmSync(GENERATED, { recursive: true, force: true })
fs.mkdirSync(GENERATED, { recursive: true })
fs.writeFileSync(path.join(GENERATED, 'embedded.ts'), `// Generated by release/build.ts.\n${imports.join('\n')}\n\n${body.join('\n\n')}\n`)

// 5. Fixes for packages that don't survive bundling as they are. Each checks the code is still what it fixes.
function patch(file: RegExp, change: (source: string) => string): BunPlugin['setup'] {
  return (b) =>
    b.onLoad({ filter: file }, async ({ path: p }) => {
      const before = await Bun.file(p).text()
      const after = change(before)
      if (after === before) throw new Error(`release/build.ts: the fix for ${p} no longer applies (the package changed)`)
      return { contents: after, loader: 'js' }
    })
}
const replace = (from: string | RegExp, to: string) => (s: string) => s.replace(from, to)
const fsVersion = JSON.parse(fs.readFileSync(at('mcp-plugins', 'node_modules', '@modelcontextprotocol', 'server-filesystem', 'package.json'), 'utf8')).version
const fixes: [RegExp, (s: string) => string][] = [
  // Bun drops the (unused) web-worker class but keeps the line naming it, which then throws.
  [/ogg-opus-decoder\/index\.js$/, () => `import OggOpusDecoder from "./src/OggOpusDecoder.js";\nimport { assignNames } from "@wasm-audio-decoders/common";\nassignNames(OggOpusDecoder, "OggOpusDecoder");\nexport { OggOpusDecoder };\n`],
  // A native binding loaded from a computed path, with its library beside it: see ort.ts.
  [/onnxruntime-node\/dist\/binding\.js$/, replace(/require\(`\.\.\/bin\/napi-v6\/[^`]*`\)/, `require(${JSON.stringify(at('release', 'ort.ts'))}).binding`)],
  // Reads its own package.json for its version.
  [/server-filesystem\/dist\/version\.js$/, replace('export function resolvePackageVersion() {', `export function resolvePackageVersion() {\n    return ${JSON.stringify(fsVersion)};`)],
  // Starts itself when it's the process entry point, which inside a bundle every module seems to be; plugins.ts starts it.
  [/server-filesystem\/dist\/index\.js$/, replace('if (isEntryPoint(process.argv[1], import.meta.url)) {', 'if (false) {')],
]

// 6. The binary.
console.log(`· ${name} (${build.id})`)
fs.rmSync(out, { recursive: true, force: true })
const result = await Bun.build({
  entrypoints: [at('release', 'main.ts')],
  target: 'bun',
  compile: { outfile: path.join(out, 'jarvis') },
  // Only for Firefox (WebDriver BiDi); Jarvis drives Chrome.
  external: ['chromium-bidi/*'],
  plugins: fixes.map(([file, change], i) => ({ name: `fix-${i}`, setup: patch(file, change) })),
})
if (!result.success) {
  for (const log of result.logs) console.error(log)
  process.exit(1)
}
fs.copyFileSync(at('release', 'env.example'), path.join(out, '.env.example'))
fs.copyFileSync(at('release', 'README.md'), path.join(out, 'README.md'))

// 7. The tarball.
const tarball = `${out}.tar.gz`
run('tar', ['-czf', tarball, '-C', path.dirname(out), name])
const sum = crypto.createHash('sha256').update(fs.readFileSync(tarball)).digest('hex')
fs.writeFileSync(`${tarball}.sha256`, `${sum}  ${path.basename(tarball)}\n`)
const mb = (f: string) => `${(fs.statSync(f).size / 1e6).toFixed(0)} MB`
console.log(`\n  ${path.relative(ROOT, path.join(out, 'jarvis'))}  ${mb(path.join(out, 'jarvis'))}\n  ${path.relative(ROOT, tarball)}  ${mb(tarball)}\n`)
